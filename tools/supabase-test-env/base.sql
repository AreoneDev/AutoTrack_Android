CREATE TABLE public.leads (
 lead_id bigserial PRIMARY KEY,
 first_name text NOT NULL DEFAULT '', last_name text NOT NULL DEFAULT '',
 phone text DEFAULT '', lead_email text DEFAULT '', lead_division text DEFAULT '',
 lead_address text DEFAULT '', lead_city text DEFAULT '', lead_province text DEFAULT 'ON',
 lead_country text DEFAULT 'Canada', lead_postal_code text DEFAULT '', budget numeric DEFAULT 0,
 stage text DEFAULT 'NEW', follow_up_date timestamp, score integer DEFAULT 0,
 notes text DEFAULT '', created_at timestamp DEFAULT now(), last_interaction_date timestamp,
 last_interaction_by text DEFAULT '', status boolean DEFAULT true
);
CREATE TABLE public.vehicles (
 vehicle_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 make text, model text, year integer, trim text, price numeric NOT NULL DEFAULT 0,
 color text, in_stock boolean NOT NULL DEFAULT false, vin text NOT NULL DEFAULT 'N/A',
 transmission text NOT NULL DEFAULT 'Automatic'
);
CREATE TABLE public.tasks (
 task_id bigserial PRIMARY KEY, lead_id bigint NOT NULL,
 title text NOT NULL, task_date timestamp NOT NULL, completed boolean DEFAULT false,
 task_type text, notes text, completed_at timestamptz,
 CONSTRAINT fk_task_lead FOREIGN KEY (lead_id) REFERENCES public.leads(lead_id) ON DELETE CASCADE
);
CREATE TABLE public.notifications (
 notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lead_id bigint, title text NOT NULL DEFAULT '', date timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.lead_vehicle_interests (
 lead_id integer PRIMARY KEY REFERENCES public.leads(lead_id) ON DELETE CASCADE,
 vehicle_id integer NOT NULL REFERENCES public.vehicles(vehicle_id),
 trim_override text, updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.lead_trade_in_vehicles (
 lead_id integer PRIMARY KEY REFERENCES public.leads(lead_id) ON DELETE CASCADE,
 vehicle_id integer NOT NULL REFERENCES public.vehicles(vehicle_id),
 trim_override text, updated_at timestamptz NOT NULL DEFAULT now()
);
